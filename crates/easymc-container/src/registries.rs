//! China-friendly container registry mirrors for rootless Podman.
//!
//! Mirror hostnames follow publicly documented DaoCloud / community prefixes —
//! service endpoints, not vendored source. The registries.conf *shape* matches
//! containers/image `registries.conf` (Apache-2.0 schema); EasyMC emits its own
//! TOML drop-in.

use std::fs;
use std::path::PathBuf;

use serde::{Deserialize, Serialize};

use crate::repair::MirrorProfile;

/// Default public image tag for MC Java runtime isolation (Temurin JRE).
pub const DEFAULT_BASE_IMAGE: &str = "docker.io/library/eclipse-temurin:21-jre";

/// DaoCloud-prefixed form of [`DEFAULT_BASE_IMAGE`] for China pulls.
pub const DEFAULT_BASE_IMAGE_MIRROR: &str =
    "docker.m.daocloud.io/library/eclipse-temurin:21-jre";

/// TOML drop-in content for DaoCloud multi-registry map.
pub fn china_friendly_registries_toml() -> String {
    r#"# Generated by EasyMC — China-friendly Podman registry mirrors
# Mirror endpoints: DaoCloud public-image-mirror (public service prefixes).
# Schema: containers-registries.conf(5)

unqualified-search-registries = ["docker.io"]

[[registry]]
location = "docker.io"

[[registry.mirror]]
location = "docker.m.daocloud.io"

[[registry]]
location = "ghcr.io"

[[registry.mirror]]
location = "ghcr.m.daocloud.io"

[[registry]]
location = "quay.io"

[[registry.mirror]]
location = "quay.m.daocloud.io"

[[registry]]
location = "gcr.io"

[[registry.mirror]]
location = "gcr.m.daocloud.io"

[[registry]]
location = "registry.k8s.io"

[[registry.mirror]]
location = "k8s.m.daocloud.io"

[[registry]]
location = "mcr.microsoft.com"

[[registry.mirror]]
location = "mcr.m.daocloud.io"
"#
    .to_string()
}

/// registries.conf drop-in for a specific mirror profile (China-friendly hosts).
pub fn registries_toml_for_profile(profile: MirrorProfile) -> Option<String> {
    let host = profile.docker_io_mirror_host()?;
    let label = profile.label_zh();
    Some(format!(
        r#"# Generated by EasyMC — container registry mirrors ({label})
# Schema: containers-registries.conf(5)

unqualified-search-registries = ["docker.io"]

[[registry]]
location = "docker.io"

[[registry.mirror]]
location = "{host}"
"#
    ))
}

/// Preferred path for EasyMC's registries drop-in (rootless user config).
pub fn registries_conf_path() -> Option<PathBuf> {
    let home = dirs::home_dir()?;
    Some(
        home.join(".config")
            .join("containers")
            .join("registries.conf.d")
            .join("easymc-china.conf"),
    )
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChinaRegistriesResult {
    pub path: String,
    pub wrote: bool,
    pub message_zh: String,
}

/// Write (or refresh) the China mirrors drop-in (DaoCloud). Idempotent.
pub fn write_china_registries_config() -> Result<ChinaRegistriesResult, String> {
    let path = registries_conf_path().ok_or_else(|| "无法定位用户目录".to_string())?;
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    let body = china_friendly_registries_toml();
    let already = fs::read_to_string(&path)
        .ok()
        .map(|s| s == body)
        .unwrap_or(false);
    if already {
        return Ok(ChinaRegistriesResult {
            path: path.to_string_lossy().into_owned(),
            wrote: false,
            message_zh: "国内镜像源配置已是最新".into(),
        });
    }
    fs::write(&path, body).map_err(|e| e.to_string())?;
    Ok(ChinaRegistriesResult {
        path: path.to_string_lossy().into_owned(),
        wrote: true,
        message_zh: "已写入国内容器镜像加速配置（DaoCloud 前缀）".into(),
    })
}

/// Write (or refresh) registries drop-in for the given profile. Official → no write.
pub fn write_registries_config_for_profile(
    profile: MirrorProfile,
) -> Result<ChinaRegistriesResult, String> {
    if matches!(profile, MirrorProfile::Official) {
        return Ok(ChinaRegistriesResult {
            path: String::new(),
            wrote: false,
            message_zh: "已选择官方源；跳过写入国内 registries 配置".into(),
        });
    }
    // DaoCloud keeps the richer multi-registry map; other CN proxies only rewrite docker.io.
    if matches!(profile, MirrorProfile::Daocloud) {
        return write_china_registries_config();
    }
    let path = registries_conf_path().ok_or_else(|| "无法定位用户目录".to_string())?;
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    let body = registries_toml_for_profile(profile)
        .ok_or_else(|| "该镜像源无需写入 registries".to_string())?;
    let already = fs::read_to_string(&path)
        .ok()
        .map(|s| s == body)
        .unwrap_or(false);
    if already {
        return Ok(ChinaRegistriesResult {
            path: path.to_string_lossy().into_owned(),
            wrote: false,
            message_zh: format!("{}配置已是最新", profile.label_zh()),
        });
    }
    fs::write(&path, body).map_err(|e| e.to_string())?;
    Ok(ChinaRegistriesResult {
        path: path.to_string_lossy().into_owned(),
        wrote: true,
        message_zh: format!("已写入容器镜像加速配置（{}）", profile.label_zh()),
    })
}

/// Rewrite a docker.io / ghcr.io / … reference to its DaoCloud prefix form when useful.
pub fn prefer_china_image_ref(image: &str, prefer_mirror: bool) -> String {
    if !prefer_mirror {
        return image.to_string();
    }
    let mappings = [
        ("docker.io/", "docker.m.daocloud.io/"),
        ("ghcr.io/", "ghcr.m.daocloud.io/"),
        ("quay.io/", "quay.m.daocloud.io/"),
        ("gcr.io/", "gcr.m.daocloud.io/"),
        ("registry.k8s.io/", "k8s.m.daocloud.io/"),
        ("mcr.microsoft.com/", "mcr.m.daocloud.io/"),
    ];
    for (from, to) in mappings {
        if let Some(rest) = image.strip_prefix(from) {
            return format!("{to}{rest}");
        }
    }
    if !image.contains('/') {
        return format!("docker.m.daocloud.io/library/{image}");
    }
    if image.starts_with("library/") {
        return format!("docker.m.daocloud.io/{image}");
    }
    image.to_string()
}

/// Rewrite an image ref for the selected mirror profile.
pub fn prefer_image_ref_for_profile(image: &str, profile: MirrorProfile) -> String {
    match profile {
        MirrorProfile::Official => image.to_string(),
        MirrorProfile::Daocloud => prefer_china_image_ref(image, true),
        MirrorProfile::Dockerproxy | MirrorProfile::Onems => {
            let Some(host) = profile.docker_io_mirror_host() else {
                return image.to_string();
            };
            if let Some(rest) = image.strip_prefix("docker.io/") {
                return format!("{host}/{rest}");
            }
            if !image.contains('/') {
                return format!("{host}/library/{image}");
            }
            if image.starts_with("library/") {
                return format!("{host}/{image}");
            }
            image.to_string()
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn toml_mentions_daocloud() {
        let t = china_friendly_registries_toml();
        assert!(t.contains("docker.m.daocloud.io"));
        assert!(t.contains("[[registry.mirror]]"));
    }

    #[test]
    fn rewrite_docker_hub() {
        assert_eq!(
            prefer_china_image_ref("docker.io/library/eclipse-temurin:21-jre", true),
            "docker.m.daocloud.io/library/eclipse-temurin:21-jre"
        );
        assert_eq!(
            prefer_china_image_ref("docker.io/library/eclipse-temurin:21-jre", false),
            "docker.io/library/eclipse-temurin:21-jre"
        );
    }

    #[test]
    fn profile_rewrite_dockerproxy() {
        let img = prefer_image_ref_for_profile(
            "docker.io/library/eclipse-temurin:21-jre",
            MirrorProfile::Dockerproxy,
        );
        assert_eq!(img, "dockerproxy.net/library/eclipse-temurin:21-jre");
    }
}
