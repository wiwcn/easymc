//! China-friendly container registry mirrors for rootless Podman.
//!
//! Mirror hostnames follow the publicly documented DaoCloud public-image-mirror
//! prefix map (https://github.com/DaoCloud/public-image-mirror) — service endpoints,
//! not vendored source. The registries.conf *shape* matches containers/image
//! `registries.conf` (Apache-2.0 schema); EasyMC emits its own TOML drop-in.

use std::fs;
use std::path::PathBuf;

use serde::{Deserialize, Serialize};

/// Default public image tag for MC Java runtime isolation (Temurin JRE).
/// Full game+mesa images land in a later slice; Slice A/B only needs a stable public tag.
pub const DEFAULT_BASE_IMAGE: &str = "docker.io/library/eclipse-temurin:21-jre";

/// DaoCloud-prefixed form of [`DEFAULT_BASE_IMAGE`] for China pulls.
pub const DEFAULT_BASE_IMAGE_MIRROR: &str =
    "docker.m.daocloud.io/library/eclipse-temurin:21-jre";

/// TOML drop-in content for `~/.config/containers/registries.conf.d/easymc-china.conf`
/// (or user main file merge). Prefer drop-in so we do not clobber a player's custom main file.
pub fn china_friendly_registries_toml() -> String {
    r#"# Generated by EasyMC — China-friendly Podman registry mirrors
# Mirror endpoints: DaoCloud public-image-mirror (public service prefixes).
# Schema: containers-registries.conf(5)

unqualified-search-registries = ["docker.io"]

[[registry]]
location = "docker.io"

[[registry.mirror]]
location = "docker.m.daocloud.io"

[[registry]]
location = "ghcr.io"

[[registry.mirror]]
location = "ghcr.m.daocloud.io"

[[registry]]
location = "quay.io"

[[registry.mirror]]
location = "quay.m.daocloud.io"

[[registry]]
location = "gcr.io"

[[registry.mirror]]
location = "gcr.m.daocloud.io"

[[registry]]
location = "registry.k8s.io"

[[registry.mirror]]
location = "k8s.m.daocloud.io"

[[registry]]
location = "mcr.microsoft.com"

[[registry.mirror]]
location = "mcr.m.daocloud.io"
"#
    .to_string()
}

/// Preferred path for EasyMC's registries drop-in (rootless user config).
pub fn registries_conf_path() -> Option<PathBuf> {
    let home = dirs::home_dir()?;
    Some(
        home.join(".config")
            .join("containers")
            .join("registries.conf.d")
            .join("easymc-china.conf"),
    )
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChinaRegistriesResult {
    pub path: String,
    pub wrote: bool,
    pub message_zh: String,
}

/// Write (or refresh) the China mirrors drop-in. Idempotent.
pub fn write_china_registries_config() -> Result<ChinaRegistriesResult, String> {
    let path = registries_conf_path().ok_or_else(|| "无法定位用户目录".to_string())?;
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    let body = china_friendly_registries_toml();
    let already = fs::read_to_string(&path)
        .ok()
        .map(|s| s == body)
        .unwrap_or(false);
    if already {
        return Ok(ChinaRegistriesResult {
            path: path.to_string_lossy().into_owned(),
            wrote: false,
            message_zh: "国内镜像源配置已是最新".into(),
        });
    }
    fs::write(&path, body).map_err(|e| e.to_string())?;
    Ok(ChinaRegistriesResult {
        path: path.to_string_lossy().into_owned(),
        wrote: true,
        message_zh: "已写入国内容器镜像加速配置（DaoCloud 前缀）".into(),
    })
}

/// Rewrite a docker.io / ghcr.io / … reference to its DaoCloud prefix form when useful.
pub fn prefer_china_image_ref(image: &str, prefer_mirror: bool) -> String {
    if !prefer_mirror {
        return image.to_string();
    }
    let mappings = [
        ("docker.io/", "docker.m.daocloud.io/"),
        ("ghcr.io/", "ghcr.m.daocloud.io/"),
        ("quay.io/", "quay.m.daocloud.io/"),
        ("gcr.io/", "gcr.m.daocloud.io/"),
        ("registry.k8s.io/", "k8s.m.daocloud.io/"),
        ("mcr.microsoft.com/", "mcr.m.daocloud.io/"),
    ];
    for (from, to) in mappings {
        if let Some(rest) = image.strip_prefix(from) {
            return format!("{to}{rest}");
        }
    }
    // Bare library image → docker.io/library/…
    if !image.contains('/') {
        return format!("docker.m.daocloud.io/library/{image}");
    }
    if image.starts_with("library/") {
        return format!("docker.m.daocloud.io/{image}");
    }
    image.to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn toml_mentions_daocloud() {
        let t = china_friendly_registries_toml();
        assert!(t.contains("docker.m.daocloud.io"));
        assert!(t.contains("[[registry.mirror]]"));
    }

    #[test]
    fn rewrite_docker_hub() {
        assert_eq!(
            prefer_china_image_ref("docker.io/library/eclipse-temurin:21-jre", true),
            "docker.m.daocloud.io/library/eclipse-temurin:21-jre"
        );
        assert_eq!(
            prefer_china_image_ref("docker.io/library/eclipse-temurin:21-jre", false),
            "docker.io/library/eclipse-temurin:21-jre"
        );
    }
}
